-- Auth profile, salon-client, administrator role, and approval foundation.
-- This migration deliberately creates no administrator account or credentials.

begin;

create table public.salon_clients (
  id bigint generated by default as identity primary key,
  salon_name text,
  contact_name text,
  phone text,
  email text,
  address text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint salon_clients_salon_name_not_blank check (
    salon_name is null or char_length(btrim(salon_name)) > 0
  ),
  constraint salon_clients_contact_name_not_blank check (
    contact_name is null or char_length(btrim(contact_name)) > 0
  ),
  constraint salon_clients_phone_not_blank check (
    phone is null or char_length(btrim(phone)) > 0
  ),
  constraint salon_clients_email_not_blank check (
    email is null or char_length(btrim(email)) > 0
  ),
  constraint salon_clients_address_not_blank check (
    address is null or char_length(btrim(address)) > 0
  )
);

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'client',
  approval_status text not null default 'pending',
  salon_client_id bigint unique references public.salon_clients(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_role_valid check (role in ('admin', 'client')),
  constraint profiles_approval_status_valid check (
    approval_status in ('pending', 'approved', 'denied')
  )
);

create index profiles_pending_client_approval_idx
  on public.profiles (created_at)
  where role = 'client' and approval_status = 'pending';

create trigger salon_clients_set_updated_at
before update on public.salon_clients
for each row execute function private.set_updated_at();

create trigger profiles_set_updated_at
before update on public.profiles
for each row execute function private.set_updated_at();

create or replace function private.is_current_user_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles as profile
    where profile.id = (select auth.uid())
      and profile.role = 'admin'
      and profile.approval_status = 'approved'
  );
$$;

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_salon_client_id bigint;
begin
  -- Contact details remain separate from Auth and are editable through
  -- public.salon_clients. Role and approval use trusted defaults only.
  insert into public.salon_clients (email)
  values (new.email)
  returning id into v_salon_client_id;

  insert into public.profiles (id, salon_client_id)
  values (new.id, v_salon_client_id);

  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function private.handle_new_user();

alter table public.salon_clients enable row level security;
alter table public.profiles enable row level security;

revoke all on table public.salon_clients, public.profiles
  from public, anon, authenticated;

revoke all on sequence public.salon_clients_id_seq
  from public, anon, authenticated;

grant select on table public.profiles to authenticated;
grant update (role, approval_status, salon_client_id) on table public.profiles to authenticated;
grant select, insert, delete on table public.salon_clients to authenticated;
grant update (salon_name, contact_name, phone, email, address)
  on table public.salon_clients to authenticated;
grant usage on sequence public.salon_clients_id_seq to authenticated;

grant usage on schema private to authenticated;
revoke all on function private.is_current_user_admin() from public, anon, authenticated;
grant execute on function private.is_current_user_admin() to authenticated;

revoke all on function private.handle_new_user() from public;

create policy "users can read own profile"
on public.profiles
for select
to authenticated
using (id = (select auth.uid()));

create policy "admins can read all profiles"
on public.profiles
for select
to authenticated
using ((select private.is_current_user_admin()));

create policy "admins can update roles approvals and profile links"
on public.profiles
for update
to authenticated
using ((select private.is_current_user_admin()))
with check ((select private.is_current_user_admin()));

create policy "users can read their linked salon client"
on public.salon_clients
for select
to authenticated
using (
  exists (
    select 1
    from public.profiles as profile
    where profile.id = (select auth.uid())
      and profile.salon_client_id = salon_clients.id
      and profile.approval_status in ('pending', 'approved')
  )
);

create policy "users can update their linked salon client"
on public.salon_clients
for update
to authenticated
using (
  exists (
    select 1
    from public.profiles as profile
    where profile.id = (select auth.uid())
      and profile.salon_client_id = salon_clients.id
      and profile.approval_status in ('pending', 'approved')
  )
)
with check (
  exists (
    select 1
    from public.profiles as profile
    where profile.id = (select auth.uid())
      and profile.salon_client_id = salon_clients.id
      and profile.approval_status in ('pending', 'approved')
  )
);

create policy "admins can manage salon clients"
on public.salon_clients
for all
to authenticated
using ((select private.is_current_user_admin()))
with check ((select private.is_current_user_admin()));

commit;
