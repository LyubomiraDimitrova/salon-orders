-- Catalog foundation only. This migration is prepared locally and has not been applied.
-- All prices are EUR including VAT. Browser writes are intentionally not granted yet.

begin;

create schema if not exists private;

create table public.brands (
  id bigint generated by default as identity primary key,
  name text not null,
  is_hidden boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint brands_name_not_blank check (char_length(btrim(name)) > 0),
  constraint brands_sort_order_non_negative check (sort_order >= 0),
  constraint brands_name_unique unique (name)
);

create table public.product_categories (
  id bigint generated by default as identity primary key,
  name text not null,
  product_group text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint product_categories_name_not_blank check (char_length(btrim(name)) > 0),
  constraint product_categories_group_valid check (
    product_group in ('dye', 'developer', 'hair_care', 'technical')
  ),
  constraint product_categories_sort_order_non_negative check (sort_order >= 0),
  constraint product_categories_group_name_unique unique (product_group, name)
);

create table public.products (
  id bigint generated by default as identity primary key,
  brand_id bigint references public.brands(id) on delete restrict,
  category_id bigint references public.product_categories(id) on delete restrict,
  article_code text,
  series_name text,
  name text not null,
  description text not null default '',
  size_label text,
  shade_number text,
  shade_name text,
  shade_color text,
  developer_concentration text,
  image_path text,
  is_hidden boolean not null default true,
  is_recommended boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint products_name_not_blank check (char_length(btrim(name)) > 0),
  constraint products_article_code_not_blank check (
    article_code is null or char_length(btrim(article_code)) > 0
  ),
  constraint products_series_name_not_blank check (
    series_name is null or char_length(btrim(series_name)) > 0
  ),
  constraint products_size_label_not_blank check (
    size_label is null or char_length(btrim(size_label)) > 0
  ),
  constraint products_developer_concentration_not_blank check (
    developer_concentration is null or char_length(btrim(developer_concentration)) > 0
  )
);

create unique index products_article_code_unique_idx
  on public.products (article_code)
  where article_code is not null;

create index products_brand_id_idx on public.products (brand_id);
create index products_category_id_idx on public.products (category_id);
create index products_catalog_listing_idx
  on public.products (category_id, is_recommended desc, name)
  where is_hidden = false;

create table private.product_prices (
  product_id bigint primary key references public.products(id) on delete restrict,
  retail_price numeric(12, 2) not null,
  salon_sale_price numeric(12, 2) generated always as (
    round(retail_price * 0.70, 2)
  ) stored,
  reference_purchase_price numeric(12, 2) generated always as (
    round(retail_price * 0.53, 2)
  ) stored,
  currency char(3) not null default 'EUR',
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint product_prices_retail_price_positive check (retail_price > 0),
  constraint product_prices_currency_eur check (currency = 'EUR')
);

create or replace function private.set_updated_at()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger brands_set_updated_at
before update on public.brands
for each row execute function private.set_updated_at();

create trigger product_categories_set_updated_at
before update on public.product_categories
for each row execute function private.set_updated_at();

create trigger products_set_updated_at
before update on public.products
for each row execute function private.set_updated_at();

create trigger product_prices_set_updated_at
before update on private.product_prices
for each row execute function private.set_updated_at();

create or replace function private.prevent_product_price_reassignment()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
begin
  if new.product_id is distinct from old.product_id then
    raise exception 'A product price row cannot be reassigned to another product'
      using errcode = 'check_violation';
  end if;

  return new;
end;
$$;

create trigger product_prices_prevent_product_reassignment
before update of product_id on private.product_prices
for each row execute function private.prevent_product_price_reassignment();

create or replace function private.assert_product_publishable(p_product_id bigint)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public, private
as $$
declare
  v_is_hidden boolean;
  v_brand_id bigint;
  v_category_id bigint;
  v_size_label text;
begin
  select p.is_hidden, p.brand_id, p.category_id, p.size_label
  into v_is_hidden, v_brand_id, v_category_id, v_size_label
  from public.products p
  where p.id = p_product_id
  for update;

  if not found or v_is_hidden then
    return;
  end if;

  if v_brand_id is null or v_category_id is null
    or v_size_label is null or char_length(btrim(v_size_label)) < 2 then
    raise exception 'Published products require a brand, category, and meaningful size or pack description'
      using errcode = 'check_violation';
  end if;

  if not exists (
    select 1
    from private.product_prices pp
    where pp.product_id = p_product_id
      and pp.retail_price > 0
  ) then
    raise exception 'Published products require a positive retail price in EUR including VAT'
      using errcode = 'check_violation';
  end if;
end;
$$;

create or replace function private.enforce_product_publication_requirements()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, private
as $$
begin
  if tg_table_schema = 'private' and tg_table_name = 'product_prices' then
    if tg_op = 'DELETE' then
      perform private.assert_product_publishable(old.product_id);
      return old;
    end if;

    perform private.assert_product_publishable(new.product_id);
    return new;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;

  perform private.assert_product_publishable(new.id);
  return new;
end;
$$;

create trigger products_require_publishable_data
after insert or update of is_hidden, brand_id, category_id, size_label
on public.products
for each row execute function private.enforce_product_publication_requirements();

create trigger product_prices_protect_published_products
after insert or update or delete
on private.product_prices
for each row execute function private.enforce_product_publication_requirements();

alter table public.brands enable row level security;
alter table public.product_categories enable row level security;
alter table public.products enable row level security;
alter table private.product_prices enable row level security;

revoke all on table public.brands, public.product_categories, public.products
  from PUBLIC, anon, authenticated;
revoke all on schema private from PUBLIC, anon, authenticated;
revoke all on table private.product_prices from PUBLIC, anon, authenticated;

grant select on table public.brands, public.product_categories, public.products
  to anon, authenticated;

create policy "public can read visible brands"
on public.brands
for select
to anon, authenticated
using (is_hidden = false);

create policy "public can read product categories"
on public.product_categories
for select
to anon, authenticated
using (true);

create policy "public can read visible products of visible brands"
on public.products
for select
to anon, authenticated
using (
  is_hidden = false
  and exists (
    select 1
    from public.brands b
    where b.id = products.brand_id
      and b.is_hidden = false
  )
);

revoke all on function private.set_updated_at() from PUBLIC;
revoke all on function private.prevent_product_price_reassignment() from PUBLIC;
revoke all on function private.assert_product_publishable(bigint) from PUBLIC;
revoke all on function private.enforce_product_publication_requirements() from PUBLIC;

commit;
