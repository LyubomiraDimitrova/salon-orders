create or replace function public.replace_approved_order_lines(
  p_request_id uuid,
  p_order_id bigint,
  p_lines jsonb
)
returns table (order_id bigint, order_number bigint, status text)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order public.orders%rowtype;
begin
  perform private.require_current_admin();
  perform private.assert_order_lines_payload(p_lines);

  if not (select private.claim_order_operation(
    p_request_id,
    'replace_lines',
    p_order_id,
    jsonb_build_object(
      'order_id', p_order_id,
      'lines', private.normalized_order_lines_payload(p_lines)
    )
  )) then
    return query
    select orders.id, orders.order_number, orders.status
    from public.orders as orders
    where orders.id = p_order_id;
    return;
  end if;

  select orders.* into v_order
  from public.orders as orders
  where orders.id = p_order_id
  for update;

  if not found then
    raise exception 'Order % does not exist', p_order_id using errcode = 'foreign_key_violation';
  end if;

  if v_order.status <> 'APPROVED' then
    raise exception 'Only APPROVED orders can have their lines changed'
      using errcode = 'check_violation';
  end if;

  perform private.lock_stock_levels_for_order_line_change(p_order_id, p_lines);
  perform private.release_active_reservations_for_order(p_order_id);

  -- A matching product keeps its product and price snapshots. Its preceding
  -- quantity is written once to the immutable audit table before amendment.
  insert into public.order_line_quantity_changes (
    order_line_id,
    previous_quantity,
    new_quantity,
    changed_by_profile_id,
    operation_request_id
  )
  select
    order_line.id,
    order_line.quantity,
    input.quantity,
    (select auth.uid()),
    p_request_id
  from public.order_lines as order_line
  join jsonb_to_recordset(p_lines) as input(product_id bigint, quantity integer)
    on input.product_id = order_line.product_id
  where order_line.order_id = p_order_id
    and order_line.is_current
    and order_line.quantity <> input.quantity;

  update public.order_lines as order_line
  set quantity = input.quantity
  from jsonb_to_recordset(p_lines) as input(product_id bigint, quantity integer)
  where order_line.order_id = p_order_id
    and order_line.product_id = input.product_id
    and order_line.is_current;

  -- Products removed from the current version retain their historical snapshots.
  update public.order_lines as order_line
  set is_current = false, replaced_at = now()
  where order_line.order_id = p_order_id
    and order_line.is_current
    and not exists (
      select 1
      from jsonb_to_recordset(p_lines) as input(product_id bigint, quantity integer)
      where input.product_id = order_line.product_id
    );

  -- The helper inserts only products that have no current line; those genuinely
