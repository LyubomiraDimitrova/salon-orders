create or replace function private.claim_order_operation(
  p_request_id uuid,
  p_operation_type text,
  p_order_id bigint,
  p_request_payload jsonb
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor_id uuid := (select auth.uid());
  v_existing private.order_operation_requests%rowtype;
  v_inserted integer;
begin
  if p_request_id is null or v_actor_id is null or p_request_payload is null
    or jsonb_typeof(p_request_payload) = 'null' then
    raise exception 'An authenticated caller, request ID, and payload are required'
      using errcode = 'not_null_violation';
  end if;

  insert into private.order_operation_requests (
    request_id, operation_type, order_id, actor_profile_id, request_payload
  )
  values (p_request_id, p_operation_type, p_order_id, v_actor_id, p_request_payload)
  on conflict (request_id) do nothing;

  get diagnostics v_inserted = row_count;
  if v_inserted = 1 then
    return true;
  end if;

  select operation_request.*
  into v_existing
  from private.order_operation_requests as operation_request
  where operation_request.request_id = p_request_id;

  if not found
    or v_existing.actor_profile_id is distinct from v_actor_id
    or v_existing.operation_type <> p_operation_type
    or (p_order_id is not null and v_existing.order_id is distinct from p_order_id)
    or v_existing.request_payload is distinct from p_request_payload then
    raise exception 'Request ID was already used for a different operation'
      using errcode = 'unique_violation';
  end if;

  return false;
end;
$$;

