  v_physical_quantity integer;
  v_reserved_quantity integer;
  v_active_quantity integer;
  v_quantity_to_reserve integer;
begin
  -- Every caller locks its order first. Product balance locks are then acquired
  -- in ascending product ID order to avoid cross-order deadlocks.
  for v_line in
    select order_line.id, order_line.product_id, order_line.quantity
    from public.order_lines as order_line
    where order_line.order_id = p_order_id
      and order_line.is_current
    order by order_line.product_id
    for update
  loop
    select stock_level.physical_quantity, stock_level.reserved_quantity
    into v_physical_quantity, v_reserved_quantity
    from public.stock_levels as stock_level
    where stock_level.product_id = v_line.product_id
    for update;

    -- No stock_levels row intentionally means unknown stock, not a confirmed zero.
    if not found then
      continue;
    end if;

    select coalesce(sum(reservation.quantity), 0)::integer
    into v_active_quantity
    from public.stock_reservations as reservation
    where reservation.order_line_id = v_line.id
      and reservation.status = 'active';

    v_quantity_to_reserve := least(
      v_line.quantity - v_active_quantity,
      v_physical_quantity - v_reserved_quantity
    );

    if v_quantity_to_reserve > 0 then
      update public.stock_levels as stock_level
      set reserved_quantity = stock_level.reserved_quantity + v_quantity_to_reserve
      where stock_level.product_id = v_line.product_id;

      insert into public.stock_reservations (
        order_line_id,
        product_id,
        quantity,
        allocated_by_profile_id,
        operation_request_id
      )
      values (
        v_line.id,
        v_line.product_id,
        v_quantity_to_reserve,
        p_actor_profile_id,
        p_request_id
      );
    end if;
  end loop;
end;
$$;

create or replace function private.lock_stock_levels_for_order_line_change(
  p_order_id bigint,
  p_new_lines jsonb
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  -- Lock the union before releasing or reserving. This gives concurrent order
  -- edits the same product-ID lock order, including products introduced by an edit.
  perform 1
  from public.stock_levels as stock_level
  where stock_level.product_id in (
    select order_line.product_id
    from public.order_lines as order_line
    where order_line.order_id = p_order_id
      and order_line.is_current

    union

    select input.product_id
    from jsonb_to_recordset(p_new_lines) as input(product_id bigint, quantity integer)
  )
  order by stock_level.product_id
  for update;
end;
$$;

create or replace function private.release_active_reservations_for_order(
  p_order_id bigint
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_reservation_total record;
begin
  for v_reservation_total in
    select reservation.product_id, sum(reservation.quantity)::integer as quantity
    from public.stock_reservations as reservation
    join public.order_lines as order_line on order_line.id = reservation.order_line_id
    where order_line.order_id = p_order_id
      and reservation.status = 'active'
    group by reservation.product_id
    order by reservation.product_id
  loop
    update public.stock_levels as stock_level
    set reserved_quantity = stock_level.reserved_quantity - v_reservation_total.quantity
    where stock_level.product_id = v_reservation_total.product_id;

    if not found then
      raise exception 'Reserved product % has no stock balance', v_reservation_total.product_id
        using errcode = 'integrity_constraint_violation';
    end if;
  end loop;

  update public.stock_reservations as reservation
  set status = 'released', released_at = now()
  from public.order_lines as order_line
  where order_line.id = reservation.order_line_id
    and order_line.order_id = p_order_id
    and reservation.status = 'active';
end;
$$;

create or replace function private.consume_reservations_for_delivery(
  p_order_id bigint,
  p_actor_profile_id uuid,
  p_request_id uuid
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if exists (
    select 1
    from public.order_lines as order_line
    left join lateral (
      select coalesce(sum(reservation.quantity), 0)::integer as active_quantity
      from public.stock_reservations as reservation
      where reservation.order_line_id = order_line.id
        and reservation.status = 'active'
    ) as active_reservation on true
    where order_line.order_id = p_order_id
      and order_line.is_current
      and active_reservation.active_quantity <> order_line.quantity
  ) then
    raise exception 'Every order line must be fully reserved before delivery'
      using errcode = 'check_violation';
  end if;

  -- Take balance locks in the same deterministic order used by reservation.
  perform 1
  from public.stock_levels as stock_level
  where stock_level.product_id in (
    select order_line.product_id
    from public.order_lines as order_line
    where order_line.order_id = p_order_id
      and order_line.is_current
  )
  order by stock_level.product_id
  for update;

  update public.stock_levels as stock_level
  set
    physical_quantity = stock_level.physical_quantity - order_line.quantity,
    reserved_quantity = stock_level.reserved_quantity - order_line.quantity
  from public.order_lines as order_line
  where order_line.order_id = p_order_id
    and order_line.is_current
    and stock_level.product_id = order_line.product_id;

  if exists (
    select 1
    from public.stock_levels as stock_level
    join public.order_lines as order_line on order_line.product_id = stock_level.product_id
    where order_line.order_id = p_order_id
      and order_line.is_current
      and (stock_level.physical_quantity < 0 or stock_level.reserved_quantity < 0)
  ) then
    raise exception 'Delivery would make stock negative'
      using errcode = 'check_violation';
  end if;

  insert into public.stock_movements (
    product_id,
    movement_type,
    quantity_delta,
    reason,
    order_id,
    order_line_id,
    created_by_profile_id,
    operation_request_id
  )
  select
    order_line.product_id,
    'delivery',
    -order_line.quantity,
    'Delivered order ' || orders.order_number::text,
    p_order_id,
    order_line.id,
    p_actor_profile_id,
    p_request_id
  from public.order_lines as order_line
  join public.orders as orders on orders.id = order_line.order_id
  where order_line.order_id = p_order_id
    and order_line.is_current;

  update public.stock_reservations as reservation
  set status = 'consumed', consumed_at = now()
  from public.order_lines as order_line
  where order_line.id = reservation.order_line_id
    and order_line.order_id = p_order_id
    and reservation.status = 'active';
end;
$$;

