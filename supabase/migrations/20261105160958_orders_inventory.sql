create or replace function public.adjust_stock(
  p_request_id uuid,
  p_product_id bigint,
  p_quantity_delta integer,
  p_reason text
)
returns table (product_id bigint, physical_quantity integer, reserved_quantity integer)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_stock public.stock_levels%rowtype;
begin
  perform private.require_current_admin();

  if p_quantity_delta is null
    or p_quantity_delta = 0
    or nullif(btrim(p_reason), '') is null then
    raise exception 'Adjustment must be non-zero and include a reason'
      using errcode = 'check_violation';
  end if;

  if not exists (select 1 from public.products as product where product.id = p_product_id) then
    raise exception 'Product % does not exist', p_product_id using errcode = 'foreign_key_violation';
  end if;

  if not (select private.claim_order_operation(
    p_request_id,
    'stock_adjustment',
    null,
    jsonb_build_object(
      'product_id', p_product_id,
      'quantity_delta', p_quantity_delta,
      'reason', nullif(btrim(p_reason), '')
    )
  )) then
    select stock_level.* into v_stock from public.stock_levels as stock_level
    where stock_level.product_id = p_product_id;
    return query select v_stock.product_id, v_stock.physical_quantity, v_stock.reserved_quantity;
    return;
  end if;

  if p_quantity_delta > 0 then
    insert into public.stock_levels as stock_level (product_id, physical_quantity)
    values (p_product_id, p_quantity_delta)
    on conflict on constraint stock_levels_pkey do update
    set physical_quantity = stock_level.physical_quantity + excluded.physical_quantity
    returning * into v_stock;
  else
    select stock_level.* into v_stock
    from public.stock_levels as stock_level
    where stock_level.product_id = p_product_id
    for update;

    if not found then
      raise exception 'Cannot reduce unknown stock for product %', p_product_id
        using errcode = 'check_violation';
    end if;

    if v_stock.physical_quantity + p_quantity_delta < v_stock.reserved_quantity then
      raise exception 'Adjustment would reduce physical stock below reserved stock'
        using errcode = 'check_violation';
    end if;

    update public.stock_levels as stock_level
    set physical_quantity = stock_level.physical_quantity + p_quantity_delta
    where stock_level.product_id = p_product_id
    returning * into v_stock;
  end if;

  insert into public.stock_movements (
    product_id, movement_type, quantity_delta, reason, created_by_profile_id, operation_request_id
  )
  values (
    p_product_id,
    'adjustment',
    p_quantity_delta,
    btrim(p_reason),
    (select auth.uid()),
    p_request_id
  );

  return query select v_stock.product_id, v_stock.physical_quantity, v_stock.reserved_quantity;
end;
$$;

