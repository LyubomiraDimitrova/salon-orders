create or replace function private.assert_order_lines_payload(p_lines jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_lines is null or p_lines = 'null'::jsonb then
    raise exception 'An order requires a non-empty array of product lines'
      using errcode = 'check_violation';
  end if;

  if jsonb_typeof(p_lines) <> 'array' then
    raise exception 'An order requires a non-empty array of product lines'
      using errcode = 'check_violation';
  end if;

  if jsonb_array_length(p_lines) = 0 then
    raise exception 'An order requires a non-empty array of product lines'
      using errcode = 'check_violation';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_lines) as input(product_id bigint, quantity integer)
    where input.product_id is null or input.quantity is null or input.quantity <= 0
  ) then
    raise exception 'Each order line requires a product and positive integer quantity'
      using errcode = 'check_violation';
  end if;

  if (
    select count(*)
    from jsonb_to_recordset(p_lines) as input(product_id bigint, quantity integer)
  ) <> (
    select count(distinct input.product_id)
    from jsonb_to_recordset(p_lines) as input(product_id bigint, quantity integer)
  ) then
    raise exception 'A product can appear only once in an order'
      using errcode = 'unique_violation';
  end if;
end;
$$;

create or replace function private.normalized_order_lines_payload(p_lines jsonb)
returns jsonb
language sql
security definer
set search_path = ''
as $$
  select jsonb_agg(
    jsonb_build_object('product_id', input.product_id, 'quantity', input.quantity)
    order by input.product_id
  )
  from jsonb_to_recordset(p_lines) as input(product_id bigint, quantity integer);
$$;

create or replace function private.insert_order_lines_and_prices(
  p_order_id bigint,
  p_lines jsonb,
  p_require_public_product boolean
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_input record;
  v_product public.products%rowtype;
  v_retail_price numeric(12, 2);
  v_salon_sale_price numeric(12, 2);
  v_reference_purchase_price numeric(12, 2);
  v_currency char(3);
  v_brand_name text;
  v_order_line_id bigint;
begin
  perform private.assert_order_lines_payload(p_lines);

  for v_input in
    select input.product_id, input.quantity
    from jsonb_to_recordset(p_lines) as input(product_id bigint, quantity integer)
    order by input.product_id
  loop
    -- During an approved-order revision, an existing current product line keeps
    -- its original product and price snapshots. Only genuinely new products pass
    -- through the snapshot lookup and receive current prices.
    if exists (
      select 1
      from public.order_lines as existing_line
      where existing_line.order_id = p_order_id
        and existing_line.product_id = v_input.product_id
        and existing_line.is_current
    ) then
      continue;
    end if;

    select product.*
    into v_product
    from public.products as product
    where product.id = v_input.product_id;

    if not found then
      raise exception 'Product % does not exist', v_input.product_id
        using errcode = 'foreign_key_violation';
    end if;

    select brand.name
    into v_brand_name
    from public.brands as brand
    where brand.id = v_product.brand_id;

    if p_require_public_product and (
      v_product.is_hidden
      or not exists (
        select 1
        from public.brands as brand
        where brand.id = v_product.brand_id
          and brand.is_hidden = false
      )
    ) then
      raise exception 'Product % is not available for website ordering', v_input.product_id
        using errcode = 'insufficient_privilege';
    end if;

    select
      product_price.retail_price,
      product_price.salon_sale_price,
      product_price.reference_purchase_price,
      product_price.currency
    into
      v_retail_price,
      v_salon_sale_price,
      v_reference_purchase_price,
      v_currency
    from private.product_prices as product_price
    where product_price.product_id = v_input.product_id;

    if not found then
      raise exception 'Product % has no current price snapshot source', v_input.product_id
        using errcode = 'not_null_violation';
    end if;

    insert into public.order_lines (
      order_id,
      product_id,
      product_name_snapshot,
      product_size_snapshot,
      product_article_code_snapshot,
      brand_name_snapshot,
      product_series_name_snapshot,
      product_shade_number_snapshot,
      product_shade_name_snapshot,
      product_developer_concentration_snapshot,
      quantity
    )
    values (
      p_order_id,
      v_input.product_id,
      v_product.name,
      v_product.size_label,
      v_product.article_code,
      v_brand_name,
      v_product.series_name,
      v_product.shade_number,
      v_product.shade_name,
      v_product.developer_concentration,
      v_input.quantity
    )
    returning id into v_order_line_id;

    insert into private.order_line_price_snapshots (
      order_line_id,
      retail_price,
      salon_sale_price,
      reference_purchase_price,
      currency
    )
    values (
      v_order_line_id,
      v_retail_price,
      v_salon_sale_price,
      v_reference_purchase_price,
      v_currency
    );
  end loop;
end;
$$;

create or replace function private.create_order_with_snapshots(
  p_salon_client_id bigint,
  p_placed_by_profile_id uuid,
  p_source text,
  p_status text,
  p_requested_delivery_date date,
  p_requested_delivery_time_from time,
  p_requested_delivery_time_to time,
  p_confirmed_delivery_date date,
  p_confirmed_delivery_time_from time,
  p_confirmed_delivery_time_to time,
  p_delivery_instructions text,
  p_customer_note text,
  p_lines jsonb,
  p_require_public_product boolean
)
returns table (order_id bigint, order_number bigint)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_salon_client public.salon_clients%rowtype;
  v_created_order_id bigint;
  v_created_order_number bigint;
begin
  perform private.assert_order_lines_payload(p_lines);

  select salon_client.*
  into v_salon_client
  from public.salon_clients as salon_client
  where salon_client.id = p_salon_client_id;

  if not found then
    raise exception 'Salon client % does not exist', p_salon_client_id
      using errcode = 'foreign_key_violation';
  end if;

  insert into public.orders (
    salon_client_id,
    placed_by_profile_id,
    source,
    status,
    requested_delivery_date,
    requested_delivery_time_from,
    requested_delivery_time_to,
    confirmed_delivery_date,
    confirmed_delivery_time_from,
    confirmed_delivery_time_to,
    salon_name_snapshot,
    contact_name_snapshot,
    phone_snapshot,
    email_snapshot,
    address_snapshot,
    delivery_instructions,
    customer_note
  )
  values (
    p_salon_client_id,
    p_placed_by_profile_id,
    p_source,
    p_status,
    p_requested_delivery_date,
    p_requested_delivery_time_from,
    p_requested_delivery_time_to,
    p_confirmed_delivery_date,
    p_confirmed_delivery_time_from,
    p_confirmed_delivery_time_to,
    v_salon_client.salon_name,
    v_salon_client.contact_name,
    v_salon_client.phone,
    v_salon_client.email,
    v_salon_client.address,
    nullif(btrim(p_delivery_instructions), ''),
    nullif(btrim(p_customer_note), '')
  )
  returning orders.id, orders.order_number into v_created_order_id, v_created_order_number;

  perform private.insert_order_lines_and_prices(
    v_created_order_id,
    p_lines,
    p_require_public_product
  );

  order_id := v_created_order_id;
  order_number := v_created_order_number;
  return next;
  return;
end;
$$;

