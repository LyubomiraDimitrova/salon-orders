create or replace function public.deliver_order(
  p_request_id uuid,
  p_order_id bigint,
  p_delivered_at timestamptz
)
returns table (order_id bigint, order_number bigint, status text, delivered_at timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order public.orders%rowtype;
begin
  perform private.require_current_admin();

  if p_delivered_at is null then
    raise exception 'Delivered timestamp is required' using errcode = 'not_null_violation';
  end if;

  if not (select private.claim_order_operation(
    p_request_id,
    'deliver',
    p_order_id,
    jsonb_build_object('order_id', p_order_id, 'delivered_at', p_delivered_at)
  )) then
    return query select orders.id, orders.order_number, orders.status, orders.delivered_at
    from public.orders as orders where orders.id = p_order_id;
    return;
  end if;

  select orders.* into v_order from public.orders as orders
  where orders.id = p_order_id for update;

  if not found then
    raise exception 'Order % does not exist', p_order_id using errcode = 'foreign_key_violation';
  end if;

  if v_order.status = 'DONE' then
    return query select v_order.id, v_order.order_number, v_order.status, v_order.delivered_at;
    return;
  end if;

  if v_order.status <> 'IN_PROGRESS' then
    raise exception 'Only IN_PROGRESS orders can be delivered'
      using errcode = 'check_violation';
  end if;

  perform private.consume_reservations_for_delivery(p_order_id, (select auth.uid()), p_request_id);

  update public.orders as orders
  set status = 'DONE', delivered_at = p_delivered_at
  where orders.id = p_order_id;
  perform private.record_order_status_event(p_order_id, 'IN_PROGRESS', 'DONE', null, p_request_id);

  return query
  select v_order.id, v_order.order_number, 'DONE'::text, p_delivered_at;
end;
$$;

