create or replace function public.allocate_waiting_order_line(
  p_request_id uuid,
  p_order_line_id bigint,
  p_quantity integer
)
returns table (order_id bigint, order_line_id bigint, newly_reserved_quantity integer)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_line public.order_lines%rowtype;
  v_order public.orders%rowtype;
  v_stock public.stock_levels%rowtype;
  v_active_quantity integer;
begin
  perform private.require_current_admin();

  if p_quantity is null or p_quantity <= 0 then
    raise exception 'Allocation quantity must be positive' using errcode = 'check_violation';
  end if;

  select order_line.* into v_line
  from public.order_lines as order_line
  where order_line.id = p_order_line_id;

  if not found then
    raise exception 'Order line % does not exist', p_order_line_id using errcode = 'foreign_key_violation';
  end if;

  if not (select private.claim_order_operation(
    p_request_id,
    'allocate',
    v_line.order_id,
    jsonb_build_object(
      'order_id', v_line.order_id,
      'order_line_id', p_order_line_id,
      'product_id', v_line.product_id,
      'quantity', p_quantity
    )
  )) then
    return query select v_line.order_id, v_line.id, 0;
    return;
  end if;

  select orders.* into v_order
  from public.orders as orders
  where orders.id = v_line.order_id
  for update;

  if not found then
    raise exception 'Order % does not exist', v_line.order_id using errcode = 'foreign_key_violation';
  end if;

  if v_order.status not in ('APPROVED', 'IN_PROGRESS') then
    raise exception 'Only approved or in-progress orders can receive allocations'
      using errcode = 'check_violation';
  end if;

  select order_line.* into v_line
  from public.order_lines as order_line
  where order_line.id = p_order_line_id
    and order_line.order_id = v_order.id
    and order_line.is_current
  for update;

  if not found then
    raise exception 'Current order line % no longer belongs to order %', p_order_line_id, v_order.id
      using errcode = 'check_violation';
  end if;

  select stock_level.* into v_stock
  from public.stock_levels as stock_level
  where stock_level.product_id = v_line.product_id
  for update;

  if not found then
    raise exception 'Stock is unknown for product %', v_line.product_id
      using errcode = 'check_violation';
  end if;

  select coalesce(sum(reservation.quantity), 0)::integer into v_active_quantity
  from public.stock_reservations as reservation
  where reservation.order_line_id = v_line.id and reservation.status = 'active';

  if p_quantity > v_line.quantity - v_active_quantity then
    raise exception 'Allocation exceeds the line shortage' using errcode = 'check_violation';
  end if;

  if p_quantity > v_stock.physical_quantity - v_stock.reserved_quantity then
    raise exception 'Allocation exceeds available stock' using errcode = 'check_violation';
  end if;

  update public.stock_levels as stock_level
  set reserved_quantity = stock_level.reserved_quantity + p_quantity
  where stock_level.product_id = v_line.product_id;

  insert into public.stock_reservations (
    order_line_id, product_id, quantity, allocated_by_profile_id, operation_request_id
  )
  values (v_line.id, v_line.product_id, p_quantity, (select auth.uid()), p_request_id);

  return query select v_line.order_id, v_line.id, p_quantity;
end;
$$;

